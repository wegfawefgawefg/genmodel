"""Writes .obj + .mtl + .png."""

import os

import numpy as np

from PIL import Image


def write_obj(out_dir, name, verts, normals, uvs, faces, texture, face_part, texture_filter="linear"):
    os.makedirs(out_dir, exist_ok=True)
    Image.fromarray(texture, "RGBA").save(os.path.join(out_dir, name + ".png"))
    with open(os.path.join(out_dir, name + ".mtl"), "w") as f:
        # the viewer reads the filter hint; other tools ignore the comment
        f.write(f"# genmodel filter {texture_filter}\nnewmtl {name}\nKd 1 1 1\nKs 0 0 0\nmap_Kd {name}.png\n")
    lines = [f"mtllib {name}.mtl\n", f"o {name}\n"]
    lines += [f"v {x:.5f} {y:.5f} {z:.5f}\n" for x, y, z in verts]
    # obj puts v = 0 at the bottom of the image, the atlas at the top
    lines += [f"vt {u:.6f} {1 - v:.6f}\n" for u, v in uvs]
    lines += [f"vn {x:.4f} {y:.4f} {z:.4f}\n" for x, y, z in normals]
    lines.append(f"usemtl {name}\n")
    # one group per rig part
    fi = faces + 1
    order = np.argsort(face_part, kind="stable")
    current = None
    for k in order:
        if face_part[k] != current:
            current = face_part[k]
            lines.append(f"g {current}\n")
        a, b, c = fi[k]
        lines.append(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}\n")
    tmp = os.path.join(out_dir, name + ".obj.tmp")
    with open(tmp, "w") as f:
        f.writelines(lines)
    os.replace(tmp, os.path.join(out_dir, name + ".obj"))


def fmt(v):
    return " ".join(f"{x:.4f}" for x in v)


def write_rig(out_dir, name, scene):
    """Parts and paths for the animator, in export units."""
    k = scene.scale
    lines = [f"; generated by gen/build.py from gen/models/{name}.py\n", f"(rig {name}\n"]
    for pt in scene.parts:
        extra = f" (parent {pt.parent})" if pt.parent else ""
        extra += " (additive)" if pt.additive else ""
        lines.append(f"  (part {pt.name} (pivot {fmt(np.asarray(pt.pivot) * k)}){extra})\n")
    for ph in scene.paths:
        pts = " ".join(f"({fmt(np.asarray(p) * k)})" for p in ph.points)
        links = " ".join(ph.links)
        lines.append(f"  (path {ph.name} (parent {ph.parent}) (points {pts})\n")
        anchor = f" (anchor {ph.anchor})" if ph.anchor else ""
        lines.append(f"    (pitch {ph.pitch * k:.4f}) (start {ph.start * k:.4f}) (across {fmt(ph.across)}){anchor}\n")
        lines.append(f"    (links {links}))\n")
    lines.append(")\n")
    with open(os.path.join(out_dir, name + ".rig.sexp"), "w") as f:
        f.writelines(lines)
